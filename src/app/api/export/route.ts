import { NextResponse } from "next/server";
import { getServerSession } from "next-auth/next";
import { authOptions } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import * as XLSX from "xlsx";

export async function GET(req: Request) {
  const session = await getServerSession(authOptions);
  if (!session || !session.user || (session.user.role !== "ADMIN" && session.user.role !== "LEADER")) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 403 });
  }

  const { searchParams } = new URL(req.url);
  const mode = searchParams.get("mode") || (searchParams.get("startDate") && searchParams.get("endDate") ? "date" : "month");
  let startDate = searchParams.get("startDate");
  let endDate = searchParams.get("endDate");
  const monthParam = searchParams.get("month");
  const yearParam = searchParams.get("year");

  try {
    let whereClause: any = {};
    let reportPeriod = "";
    let filename = "";

    const pad = (n: number) => String(n).padStart(2, "0");

    if (mode === "date" && startDate && endDate) {
      // Ensure startDate <= endDate
      if (startDate > endDate) {
        const temp = startDate;
        startDate = endDate;
        endDate = temp;
      }

      const [sYear, sMonth, sDay] = startDate.split("-").map(Number);
      const [eYear, eMonth, eDay] = endDate.split("-").map(Number);

      const startDateTime = new Date(sYear, sMonth - 1, sDay, 0, 0, 0, 0);
      const endDateTime = new Date(eYear, eMonth - 1, eDay, 23, 59, 59, 999);

      // Collect all month & year combinations that fall within this range
      const periods: { year: number; month: number }[] = [];
      let currY = sYear;
      let currM = sMonth;
      while (currY < eYear || (currY === eYear && currM <= eMonth)) {
        periods.push({ year: currY, month: currM });
        currM++;
        if (currM > 12) {
          currM = 1;
          currY++;
        }
      }

      whereClause = {
        OR: [
          ...periods.map((p) => ({ month: p.month, year: p.year })),
          {
            createdAt: {
              gte: startDateTime,
              lte: endDateTime,
            },
          },
        ],
      };

      reportPeriod = `${pad(sDay)}/${pad(sMonth)}/${sYear} - ${pad(eDay)}/${pad(eMonth)}/${eYear}`;
      filename = `FCMM_Report_${startDate}_sd_${endDate}.xlsx`;
    } else {
      const month = parseInt(monthParam || String(new Date().getMonth() + 1));
      const year = parseInt(yearParam || String(new Date().getFullYear()));
      whereClause = { month, year };
      reportPeriod = `Bulan ${month}/${year}`;
      filename = `FCMM_Report_${year}_${pad(month)}.xlsx`;
    }

    const records = await prisma.record.findMany({
      where: whereClause,
      include: { user: { select: { name: true, username: true } } },
      orderBy: [
        { year: "asc" },
        { month: "asc" },
        { user: { name: "asc" } },
        { category: "asc" },
        { colorMode: "asc" },
      ],
    });

    // Format timestamp nicely
    const generatedAt = new Date().toLocaleString("id-ID", {
      dateStyle: "full",
      timeStyle: "long",
    });
    const generatedBy = session.user?.name || session.user?.email || "Administrator";

    // 1. Create Header (AOA)
    const headerInfo = [
      ["FCMM SYSTEM - OPERATIONAL AUDIT REPORT"],
      [""],
      ["Report Period", reportPeriod],
      ["Generated By", generatedBy],
      ["Generated Date", generatedAt],
      [""], // Empty row before data table
    ];

    const exportData = records.map((r: any, idx: number) => {
      // Calculate usages
      const w1Usage = (r.week1 != null && r.initial != null) ? r.week1 - r.initial : null;
      const w2Usage = (r.week2 != null && r.week1 != null) ? r.week2 - r.week1 : null;
      const w3Usage = (r.week3 != null && r.week2 != null) ? r.week3 - r.week2 : null;
      const w4Usage = (r.week4 != null && r.week3 != null) ? r.week4 - r.week3 : null;
      const w5Usage = (r.week5 != null && r.week4 != null) ? r.week5 - r.week4 : null;

      let lastVal = null;
      if (r.week5 != null) lastVal = r.week5;
      else if (r.week4 != null) lastVal = r.week4;
      else if (r.week3 != null) lastVal = r.week3;
      else if (r.week2 != null) lastVal = r.week2;
      else if (r.week1 != null) lastVal = r.week1;

      const totalUsage = (lastVal != null && r.initial != null) ? lastVal - r.initial : 0;

      return {
        "No": idx + 1,
        "Period": `${r.month}/${r.year}`,
        "User / Department": r.user?.name || r.user?.username || "-",
        "Category": r.category,
        "Color Mode": r.colorMode,
        "Initial Meter": r.initial,
        "W1 Meter": r.week1,
        "W1 Usage": w1Usage,
        "W2 Meter": r.week2,
        "W2 Usage": w2Usage,
        "W3 Meter": r.week3,
        "W3 Usage": w3Usage,
        "W4 Meter": r.week4,
        "W4 Usage": w4Usage,
        "W5 Meter": r.week5,
        "W5 Usage": w5Usage,
        "Total Usage": totalUsage,
      };
    });

    const worksheet = XLSX.utils.aoa_to_sheet(headerInfo);

    if (exportData.length === 0) {
      XLSX.utils.sheet_add_aoa(
        worksheet,
        [
          [
            "No",
            "Period",
            "User / Department",
            "Category",
            "Color Mode",
            "Initial Meter",
            "W1 Meter",
            "W1 Usage",
            "W2 Meter",
            "W2 Usage",
            "W3 Meter",
            "W3 Usage",
            "W4 Meter",
            "W4 Usage",
            "W5 Meter",
            "W5 Usage",
            "Total Usage",
          ],
          [
            "-",
            "-",
            "Tidak ada data pada periode / rentang tanggal yang dipilih",
            "-",
            "-",
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
            null,
          ],
        ],
        { origin: "A7" }
      );
    } else {
      XLSX.utils.sheet_add_json(worksheet, exportData, { origin: "A7" });

      const N = exportData.length;
      const startRow = 8;          // 1-based row index for first data row
      const endRow = 7 + N;        // 1-based row index for last data row
      const totalRow = endRow + 1; // 1-based row index for Total row

      const cols = Object.keys(exportData[0]);
      const numericCols = [
        "Initial Meter",
        "W1 Meter",
        "W1 Usage",
        "W2 Meter",
        "W2 Usage",
        "W3 Meter",
        "W3 Usage",
        "W4 Meter",
        "W4 Usage",
        "W5 Meter",
        "W5 Usage",
        "Total Usage",
      ];

      // Build Total row with dynamic Excel SUBTOTAL formulas
      // Function 109 automatically ignores hidden rows when filtered by column AutoFilter!
      const totalRowData = cols.map((key, cIdx) => {
        const colLetter = XLSX.utils.encode_col(cIdx);
        if (key === "User / Department") {
          return { t: "s", v: "TOTAL" };
        }
        if (numericCols.includes(key)) {
          const sum = exportData.reduce((acc, row: any) => acc + (Number(row[key]) || 0), 0);
          return {
            t: "n",
            f: `SUBTOTAL(109,${colLetter}${startRow}:${colLetter}${endRow})`,
            v: sum,
            z: "#,##0",
          };
        }
        return { t: "s", v: "" };
      });

      XLSX.utils.sheet_add_aoa(worksheet, [totalRowData], { origin: `A${totalRow}` });

      // Apply integer number format #,##0 to data cells
      for (let rIdx = 0; rIdx < N; rIdx++) {
        const rowNum = startRow + rIdx;
        cols.forEach((key, cIdx) => {
          if (numericCols.includes(key)) {
            const cellRef = XLSX.utils.encode_cell({ r: rowNum - 1, c: cIdx });
            if (worksheet[cellRef] && worksheet[cellRef].t === "n") {
              worksheet[cellRef].z = "#,##0";
            }
          }
        });
      }

      // Enable Excel AutoFilter for columns A7 to last column of data (excluding total row)
      const lastColLetter = XLSX.utils.encode_col(cols.length - 1);
      worksheet["!autofilter"] = {
        ref: `A7:${lastColLetter}${endRow}`,
      };
    }

    // Set auto-width for all columns
    const colWidths = [
      { wch: 6 },  // No
      { wch: 12 }, // Period
      { wch: 30 }, // User / Department
      { wch: 14 }, // Category
      { wch: 14 }, // Color Mode
      { wch: 15 }, // Initial Meter
      { wch: 13 }, // W1 Meter
      { wch: 13 }, // W1 Usage
      { wch: 13 }, // W2 Meter
      { wch: 13 }, // W2 Usage
      { wch: 13 }, // W3 Meter
      { wch: 13 }, // W3 Usage
      { wch: 13 }, // W4 Meter
      { wch: 13 }, // W4 Usage
      { wch: 13 }, // W5 Meter
      { wch: 13 }, // W5 Usage
      { wch: 16 }, // Total Usage
    ];
    worksheet["!cols"] = colWidths;

    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(workbook, worksheet, "Usage Report");

    const buf = XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });

    const response = new NextResponse(buf, {
      status: 200,
      headers: {
        "Content-Disposition": `attachment; filename="${filename}"`,
        "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      },
    });

    // Explicitly free memory for low-RAM VPS
    exportData.length = 0;
    records.length = 0;

    return response;
  } catch (error) {
    console.error(error);
    return NextResponse.json({ error: "Failed to generate report" }, { status: 500 });
  }
}
